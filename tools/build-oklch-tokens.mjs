/**
 * Builds the OKLCH token set in src/core/tokens/oklch/ by rewriting the HSL
 * color token files with the values in tools/oklch-values.json. Everything
 * else (token names, comments, dark mode blocks) is copied as is, so the two
 * sets stay in sync. Run `yarn oklch-values` first if the HSL defaults changed.
 *
 *   --op-color-primary-s: 58%;  ->  --op-color-primary-c: 0.146;
 *
 *   --op-color-primary-plus-five: light-dark(
 *     hsl(var(--op-color-primary-h) var(--op-color-primary-s) 90%),
 *     hsl(var(--op-color-primary-h) var(--op-color-primary-s) 24%)
 *   );
 *   ->
 *   --op-color-primary-plus-five: light-dark(
 *     oklch(92.3% calc(var(--op-color-primary-c) * 0.29) var(--op-color-primary-h)),
 *     oklch(29.9% calc(var(--op-color-primary-c) * 0.5) var(--op-color-primary-h))
 *   );
 */
import fs from 'node:fs'

const TOKENS_DIR = 'src/core/tokens'
const OUTPUT_DIR = `${TOKENS_DIR}/oklch`
const { defaults, steps } = JSON.parse(fs.readFileSync('tools/oklch-values.json', 'utf8'))

const colorNames = Object.keys(defaults).join('|')
const header = (file) => `/* Generated by tools/build-oklch-tokens.mjs from ../${file}. Do not edit by hand. */\n`

function chroma(name, taper) {
  return taper === 0 ? '0' : `calc(var(--op-color-${name}-c) * ${taper})`
}

function stepColor(name, { l, taper }) {
  return `oklch(${l}% ${chroma(name, taper)} var(--op-color-${name}-h))`
}

function convertShared(css) {
  return css
    .replace(/hsl\(0deg 100% 100%\)/g, 'oklch(100% 0 0)')
    .replace(/hsl\(0deg 0% 0%( \/ [\d.]+%)?\)/g, 'oklch(0% 0 0$1)')
    .replace(
      new RegExp(
        `hsl\\(var\\(--op-color-(${colorNames})-h\\) var\\(--op-color-\\1-s\\) var\\(--op-color-\\1-l\\)\\)`,
        'g'
      ),
      'oklch(var(--op-color-$1-l) var(--op-color-$1-c) var(--op-color-$1-h))'
    )
}

function convertBaseColors(css) {
  const isReference = (value) => value.startsWith('var(')
  return convertShared(css)
    .replace('/* Color HSLs', '/* Color OKLCH values')
    .replace(new RegExp(`--op-color-(${colorNames})-h: ([^;]+);`, 'g'), (match, name, value) =>
      isReference(value) ? match : `--op-color-${name}-h: ${defaults[name].h};`
    )
    .replace(
      new RegExp(`--op-color-(${colorNames})-s: [^;]+;`, 'g'),
      (_match, name) => `--op-color-${name}-c: ${defaults[name].c};`
    )
    .replace(new RegExp(`--op-color-(${colorNames})-l: ([^;]+);`, 'g'), (match, name, value) =>
      isReference(value) ? match : `--op-color-${name}-l: ${defaults[name].l}%;`
    )
}

function convertScaleColors(css) {
  const scaleToken = new RegExp(
    `--op-color-(${colorNames})-([a-z-]+): light-dark\\(\\s*hsl\\([^)]*\\)[^)]*\\)[^)]*\\),\\s*hsl\\([^)]*\\)[^)]*\\)[^)]*\\)\\s*\\)`,
    'g'
  )
  return convertShared(css).replace(scaleToken, (_match, name, step) => {
    if (!steps[step]) throw new Error(`No OKLCH values for step "${step}" (--op-color-${name}-${step})`)

    return [
      `--op-color-${name}-${step}: light-dark(`,
      `    ${stepColor(name, steps[step].light)},`,
      `    ${stepColor(name, steps[step].dark)}`,
      '  )',
    ].join('\n')
  })
}

const conversions = {
  'base_color_tokens.css': convertBaseColors,
  'scale_color_tokens.css': convertScaleColors,
}

fs.mkdirSync(OUTPUT_DIR, { recursive: true })
for (const [file, convert] of Object.entries(conversions)) {
  const output = convert(fs.readFileSync(`${TOKENS_DIR}/${file}`, 'utf8'))
  const leftover = output.match(/.*(hsl\(|-s[:)]).*/)
  if (leftover) throw new Error(`Unconverted HSL left in ${file}: ${leftover[0].trim()}`)

  fs.writeFileSync(`${OUTPUT_DIR}/${file}`, header(file) + output)
  console.log(`Wrote ${OUTPUT_DIR}/${file}`)
}
